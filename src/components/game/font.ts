export const GLYPH_W = 5;
export const GLYPH_H = 7;
const TRACK = 1;

export function textWidth(text: string) {
  if (!text.length) return 0;
  return text.length * (GLYPH_W + TRACK) - TRACK;
}

/**
 * Draws pixel text with its top-left at (x, y).
 * `shadow` paints a 1px drop first, which is what keeps small text legible
 * against a busy wooden board.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  shadow?: string,
) {
  const chars = text.toUpperCase().split("");

  const paint = (offX: number, offY: number, fill: string) => {
    ctx.fillStyle = fill;
    let cursor = x + offX;
    for (const ch of chars) {
      const glyph = GLYPHS[ch] ?? GLYPHS["."];
      for (let row = 0; row < GLYPH_H; row++) {
        const bits = glyph[row];
        if (!bits) continue;
        for (let col = 0; col < GLYPH_W; col++) {
          if (bits & (1 << (GLYPH_W - 1 - col))) {
            ctx.fillRect(cursor + col, y + offY + row, 1, 1);
          }
        }
      }
      cursor += GLYPH_W + TRACK;
    }
  };

  if (shadow) paint(1, 1, shadow);
  paint(0, 0, color);
}
